#!/usr/bin/env bash
# Refresh web/.env.local against PrescribeRx public sandbox tokens.
# Tokens rotate every 12h: https://demo.prescribe-rx.com/api/docs/tokens
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
WEB="$ROOT/web"
TOKENS_JSON="$(curl -fsSL https://demo.prescribe-rx.com/api/docs/tokens)"
# system_admin is the only public playground type that can still read
# /telehealth/encounter-types. sales_organization and client return 403.
TOKEN="$(python3 -c 'import json,sys; print(json.load(sys.stdin)["tokens"]["system_admin"])' <<<"$TOKENS_JSON")"
cat > "$WEB/.env.local" <<EOF
# Local sandbox only. Do not commit. Regenerated by build/tools/refresh-prescriberx-sandbox.sh
PRESCRIBERX_API_BASE=https://demo.prescribe-rx.com/api/v1
PRESCRIBERX_API_TOKEN=$TOKEN
PRESCRIBERX_SANDBOX=true
PRESCRIBERX_DEFAULT_ENCOUNTER_TYPE_ID=019ce396-46a1-73ab-87d6-c40310555401
ASK_TIDL_MODE_DEFAULT=marketing
EOF
echo "Wrote $WEB/.env.local (system_admin sandbox token)"
